def safe_keep(elements: list):
    total = 0
    for el in elements:
        _, h = el.wrap(AVAIL_W, PAGE_H)
        total += h
    if total <= PAGE_H * 0.40:
        return [KeepTogether(elements)]
    if len(elements) >= 2:
        return [KeepTogether(elements[:2])] + elements[2:]
    return elements


def table(header: list[str], rows: list[list[str]], ratios: list[float], caption: str = "", center_cols: list[int] | None = None):
    center_cols = center_cols or []
    assert abs(sum(ratios) - 1) < 0.00001
    data = [[Paragraph(f"<b>{cell}</b>", st_th) for cell in header]]
    for row in rows:
        data.append([
            Paragraph(cell, st_td_c if j in center_cols else st_td)
            for j, cell in enumerate(row)
        ])
    t = Table(data, colWidths=[AVAIL_W * ratio for ratio in ratios], repeatRows=1, hAlign="CENTER")
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.45, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4.2),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4.2),
        ("TOPPADDING", (0, 0), (-1, -1), 4.2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4.2),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i), colors.white if i % 2 else TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 10), t]
    if caption:
        out.append(Paragraph(caption, st_cap))
    out.append(Spacer(1, 10))
    return out


def callout(story: list, title: str, body: str, color=ACCENT):
    big = ParagraphStyle(
        "CalloutTitle_" + hashlib.md5(title.encode("utf-8")).hexdigest()[:8],
        fontName="Microsoft YaHei-Bold", fontSize=13.0, leading=19, textColor=color,
        alignment=TA_CENTER, wordWrap="CJK",
    )
    copy = ParagraphStyle(
        "CalloutBody_" + hashlib.md5(body.encode("utf-8")).hexdigest()[:8],
        fontName="SimHei", fontSize=9.7, leading=15.2, textColor=TEXT_PRIMARY,
        alignment=TA_LEFT, wordWrap="CJK",
    )
    card = Table(
        [[Paragraph(f"<b>{title}</b>", big)], [Paragraph(body, copy)]],
        colWidths=[AVAIL_W * 0.92], hAlign="CENTER",
    )
    card.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 0.8, color),
        ("LINEBEFORE", (0, 0), (0, -1), 4, color),
        ("TOPPADDING", (0, 0), (-1, 0), 9),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 3),
        ("TOPPADDING", (0, 1), (-1, 1), 3),
        ("BOTTOMPADDING", (0, 1), (-1, 1), 9),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
    ]))
    story.extend([Spacer(1, 8)] + safe_keep([card]) + [Spacer(1, 8)])


def figure(path: Path, caption: str, max_width: float = AVAIL_W * 0.90, max_height: float = 255):
    reader = ImageReader(str(path))
    width, height = reader.getSize()
    scale = min(max_width / width, max_height / height)
    image = Image(str(path), width=width * scale, height=height * scale, hAlign="CENTER")
    return [Spacer(1, 18)] + safe_keep([image, Paragraph(caption, st_cap)]) + [Spacer(1, 16)]


