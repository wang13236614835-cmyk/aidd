def heading(text: str, level: int) -> Paragraph:
    key = "h_" + hashlib.md5(text.encode("utf-8")).hexdigest()[:8]
    style = st_h1 if level == 0 else st_h2
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


